// Argv golden corpus.
//
// sglang-backend-remediation Phase 3 changes three things that touch the
// launch command line -- `--tp` -> `--tp-size`, `%.2f` -> `%.4f` on the
// memory fraction, and a new `--served-model-name` -- and each was
// argued to be a no-op or a strict improvement. This corpus converts that
// argument into a checked diff: every entrypoint is rendered across a
// matrix of launch configs and compared byte-for-byte against a frozen
// file.
//
// It is deliberately NOT a set of hand-written expectations. Those encode
// what the author believed; a golden file encodes what the code did, so a
// change nobody intended shows up as a diff in review rather than as a
// silent behaviour shift on the next cold start.
//
// Regenerate INTENTIONALLY after reviewing the diff:
//
//	go test ./gpu-arbiter -run TestArgvGoldenCorpus -update
//
// Generalises the technique already used by
// `make test-probe-ollama-idempotent`.

var updateGolden = flag.Bool("update", false, "rewrite the argv golden corpus")

