func renderGoldenCorpus() string {
	var b strings.Builder
	b.WriteString("# argv golden corpus -- generated by TestArgvGoldenCorpus -update\n")
	b.WriteString("# One block per (backend, case). Review diffs; do not edit by hand.\n")
	for _, backend := range []string{"ollama", "vllm", "sglang"} {
		entry := map[string]func(string, launchConfig) []string{
			"ollama": ollamaEntrypoint,
			"vllm":   vllmEntrypoint,
			"sglang": sglangEntrypoint,
		}[backend]
		for _, tc := range goldenCases() {
			b.WriteString("\n== " + backend + " / " + tc.Name + "\n")
			argv := entry(tc.Model, tc.LC)
			enc, err := json.MarshalIndent(argv, "", "  ")
			if err != nil {
				b.WriteString("ERROR: " + err.Error() + "\n")
				continue
			}
			b.Write(enc)
			b.WriteString("\n")
		}
	}
	return b.String()
}

func TestArgvGoldenCorpus(t *testing.T) {
	path := filepath.Join("testdata", "argv-golden.txt")
	got := renderGoldenCorpus()

	if *updateGolden {
		if err := os.MkdirAll("testdata", 0o755); err != nil {
			t.Fatalf("mkdir testdata: %v", err)
		}
		if err := os.WriteFile(path, []byte(got), 0o644); err != nil {
			t.Fatalf("write golden: %v", err)
		}
		t.Logf("golden corpus rewritten: %s", path)
		return
	}

	want, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read golden (run with -update to create): %v", err)
	}
	if got != string(want) {
		t.Errorf("argv changed against the frozen corpus.\n"+
			"If the change is INTENDED, review the diff and re-run:\n"+
			"  go test ./gpu-arbiter -run TestArgvGoldenCorpus -update\n\n%s",
			firstDiff(string(want), got))
	}
}

// firstDiff reports the first differing line with a little context, which
// is far more useful in CI output than dumping two multi-KB blobs.
func firstDiff(want, got string) string {
	w := strings.Split(want, "\n")
	g := strings.Split(got, "\n")
	for i := 0; i < len(w) || i < len(g); i++ {
		var wl, gl string
		if i < len(w) {
			wl = w[i]
		}
		if i < len(g) {
			gl = g[i]
		}
		if wl != gl {
			ctx := ""
			if i > 0 && i-1 < len(w) {
				ctx = "  context: " + w[i-1] + "\n"
			}
			return ctx +
				"  line " + itoa(i+1) + "\n" +
				"    want: " + wl + "\n" +
				"    got:  " + gl + "\n"
		}
	}
	return "  (no line differs; trailing-newline mismatch)"
}
